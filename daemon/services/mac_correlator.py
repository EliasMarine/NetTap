"""
NetTap MACCorrelator — Detect randomized MAC addresses and correlate devices.

Detects locally-administered (randomized) MACs, builds behavioral fingerprints
from DNS patterns, JA3 TLS fingerprints, destination IPs, timing, and traffic
volume. Suggests device merges with confidence scores.

A locally-administered MAC has bit 1 of the first octet set:
    int(mac.split(':')[0], 16) & 0x02 != 0
"""

