    # ------------------------------------------------------------------
    # Merge / undo
    # ------------------------------------------------------------------

    def merge_devices(self, mac_randomized: str, mac_real: str) -> dict[str, Any]:
        """Record a device merge (randomized MAC -> real MAC).

        This creates a merge record that can be used by the device registry
        to consolidate traffic and device information.
        """
        merge_record = {
            "id": str(uuid.uuid4()),
            "mac_randomized": mac_randomized.lower(),
            "mac_real": mac_real.lower(),
            "merged_at": datetime.now(timezone.utc).isoformat(),
            "status": "active",
        }

        self._merge_history.append(merge_record)
        self._save_merge_history()

        logger.info(
            "Merged randomized MAC %s -> real MAC %s",
            mac_randomized,
            mac_real,
        )
        return merge_record

    def undo_merge(self, merge_id: str) -> bool:
        """Undo a previous merge by marking it inactive."""
        for record in self._merge_history:
            if record.get("id") == merge_id:
                record["status"] = "undone"
                record["undone_at"] = datetime.now(timezone.utc).isoformat()
                self._save_merge_history()
                logger.info("Undid merge %s", merge_id)
                return True
        return False

    def get_merge_history(self) -> list[dict[str, Any]]:
        """Return all merge records (active and undone)."""
        return list(self._merge_history)

    def get_active_merges(self) -> dict[str, str]:
        """Return a dict mapping randomized MAC -> real MAC for active merges."""
        return {
            r["mac_randomized"]: r["mac_real"]
            for r in self._merge_history
            if r.get("status") == "active"
        }
