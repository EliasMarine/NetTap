# Default paths — overridable via env vars for testing
DATA_DIR = os.environ.get("NETTAP_DATA_DIR", "/opt/nettap/data")
CAPTURE_MODE_CONF = os.path.join(DATA_DIR, "capture-mode.conf")
ENV_FILE = os.environ.get("NETTAP_ENV_FILE", os.path.join(DATA_DIR, ".env"))

CAPTURE_MODES = ("dhcp_gateway", "mirror", "bridge")
DEFAULT_DHCP_SUBNET = CaptureConfig().dhcp_subnet


def _write_capture_mode_conf(config: dict) -> str:
    """Write capture-mode.conf with the selected mode and interfaces.

    Returns the path written to.
    """
    lines = [
        "# NetTap capture mode configuration",
        "# Generated by setup wizard",
        f"CAPTURE_MODE={config['capture_mode']}",
    ]

    if config["capture_mode"] == "mirror":
        lines.append(f"CAPTURE_INTERFACE={config.get('capture_interface', '')}")
        mgmt = config.get("management_interface", "")
        if mgmt:
            lines.append(f"MANAGEMENT_INTERFACE={mgmt}")
    else:
        lines.append(f"WAN_INTERFACE={config.get('wan_interface', '')}")
        lines.append(f"LAN_INTERFACE={config.get('lan_interface', '')}")

    os.makedirs(os.path.dirname(CAPTURE_MODE_CONF), exist_ok=True)
    with open(CAPTURE_MODE_CONF, "w") as f:
        f.write("\n".join(lines) + "\n")

    return CAPTURE_MODE_CONF


def _update_env_file(config: dict) -> str:
    """Append/update capture-related env vars in the .env file.

    Returns the path written to.
    """
    env_vars = {}

    env_vars["CAPTURE_MODE"] = config["capture_mode"]

    if config["capture_mode"] == "mirror":
        env_vars["CAPTURE_INTERFACE"] = config.get("capture_interface", "")
        mgmt = config.get("management_interface", "")
        if mgmt:
            env_vars["MANAGEMENT_INTERFACE"] = mgmt
    else:
        env_vars["WAN_IFACE"] = config.get("wan_interface", "")
        env_vars["LAN_IFACE"] = config.get("lan_interface", "")

    # Storage settings
    storage = config.get("storage", {})
    if storage:
        if "hot_days" in storage:
            env_vars["RETENTION_HOT"] = str(storage["hot_days"])
        if "warm_days" in storage:
            env_vars["RETENTION_WARM"] = str(storage["warm_days"])
        if "cold_days" in storage:
            env_vars["RETENTION_COLD"] = str(storage["cold_days"])
        if "disk_threshold_percent" in storage:
            env_vars["DISK_THRESHOLD_PERCENT"] = str(storage["disk_threshold_percent"])
        if "emergency_threshold_percent" in storage:
            env_vars["EMERGENCY_THRESHOLD_PERCENT"] = str(
                storage["emergency_threshold_percent"]
            )

    # Read existing .env if it exists
    existing_lines = []
    existing_keys = set()
    env_path = Path(ENV_FILE)
    if env_path.exists():
        with open(env_path, "r") as f:
            for line in f:
                stripped = line.strip()
                if stripped and not stripped.startswith("#") and "=" in stripped:
                    key = stripped.split("=", 1)[0]
                    if key in env_vars:
                        # Replace with new value
                        existing_lines.append(f"{key}={env_vars[key]}\n")
                        existing_keys.add(key)
                    else:
                        existing_lines.append(line)
                else:
                    existing_lines.append(line)

    # Append any new vars not already in the file
    for key, value in env_vars.items():
        if key not in existing_keys:
            existing_lines.append(f"{key}={value}\n")

    os.makedirs(os.path.dirname(ENV_FILE), exist_ok=True)
    with open(ENV_FILE, "w") as f:
        f.writelines(existing_lines)

    return ENV_FILE


def _build_capture_config(body: dict) -> CaptureConfig:
    """The CaptureConfig for the wizard's choice. Raises ValueError on bad input.

    CR-165 / CR-166: interface names (every mode) and the DHCP subnet are
    validated here, before anything is written.
    """
    mode = body["capture_mode"]
    if mode == "bridge":
        return CaptureConfig(
            mode=CaptureMode.BRIDGE,
            wan_interface=validate_interface_name(body.get("wan_interface")),
            lan_interface=validate_interface_name(body.get("lan_interface")),
        )
    interface = validate_interface_name(body.get("capture_interface"))
    if mode == "mirror":
        mgmt = body.get("management_interface") or ""
        return CaptureConfig(
            mode=CaptureMode.MIRROR,
            interface=interface,
            management=validate_interface_name(mgmt) if mgmt else "",
        )
    subnet = body.get("dhcp_subnet")
    return CaptureConfig(
        mode=CaptureMode.DHCP_GATEWAY,
        interface=interface,
        dhcp_subnet=validate_subnet(DEFAULT_DHCP_SUBNET if subnet is None else subnet),
    )


